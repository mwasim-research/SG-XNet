"""Export every node split used in the paper to splits/splits_v2.npz (node indices; test = all other nodes).

Keys (arrays of node indices, int32):
  eval/<target>/k<k>/s<i>/{train,val}      evaluation splits (k labels per class, 30 validation nodes per class), i = 0..9
  evalk/<target>/k<k>/s<i>/{train,val}     source-only check: k validation nodes per class (k = 1, 5; aligned targets)
  tune/<dataset>/s<i>/{train,val}          tuning splits (k = 20, seed 1000 + i), i = 0..2
  source/<dataset>/s<i>/{train,val,test}   stratified 80/10/10 source splits used for pretraining, seed i = 0..9
The splits are generated by sgx.splits with the same seeds as the experiments, so this file is a convenience copy.
Usage: python scripts/export_splits.py [--root PROJECT_FOLDER_WITH_data/]
"""
import argparse, os, sys
import numpy as np
ap = argparse.ArgumentParser(); ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "splits", "splits_v2.npz"))
a = ap.parse_args()
sys.path.insert(0, a.root)
from sgx import data, splits, jobs  # noqa: E402
import importlib.util  # noqa: E402
_tw = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posthoc", "twitch_2026-10-28", "twitch.py")
_spec = importlib.util.spec_from_file_location("twitch_posthoc", _tw); _m = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_m); _m.register()  # registers the three Twitch graphs with sgx.data (sgx is already imported)

def idx(m):
    return np.flatnonzero(np.asarray(m)).astype(np.int32)

out = {}
targets = sorted({t for _, t in jobs.ALL_PAIRS} | {"twitch_de", "twitch_engb", "twitch_fr"})
sources = sorted({s for s, _ in jobs.ALL_PAIRS} | {"twitch_de", "twitch_engb", "twitch_fr"})
aligned = ["acmv9", "citationv1", "dblpv7"]
for t in targets:
    g = data.load(t)
    for k in [1, 3, 5, 10, 20]:
        for s in range(10):
            m = splits.budget_split(g.y_np, k, seed=s, multilabel=g.multilabel)
            out[f"eval/{t}/k{k}/s{s}/train"], out[f"eval/{t}/k{k}/s{s}/val"] = idx(m["train"]), idx(m["val"])
            if t in aligned and k in (1, 5):
                m = splits.budget_split(g.y_np, k, seed=s, multilabel=g.multilabel, val_per_class=k)
                out[f"evalk/{t}/k{k}/s{s}/train"], out[f"evalk/{t}/k{k}/s{s}/val"] = idx(m["train"]), idx(m["val"])
for d in sorted(set(jobs.TUNE_DATASETS["budget20"]) | {"twitch_de", "twitch_engb", "twitch_fr"}):
    g = data.load(d)
    for s in range(3):
        m = splits.budget_split(g.y_np, 20, seed=1000 + s, multilabel=g.multilabel)
        out[f"tune/{d}/s{s}/train"], out[f"tune/{d}/s{s}/val"] = idx(m["train"]), idx(m["val"])
for d in sources:
    g = data.load(d)
    for s in range(10):
        m = splits.ratio_split(g.y_np, seed=s, multilabel=g.multilabel)
        for part in ("train", "val", "test"):
            out[f"source/{d}/s{s}/{part}"] = idx(m[part])
os.makedirs(os.path.dirname(a.out), exist_ok=True)
np.savez_compressed(a.out, **out)
print(len(out), "arrays ->", a.out)
